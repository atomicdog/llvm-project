#ifndef LLVM_LIB_TARGET_HCS08_MCTARGETDESC_HCS08INSTPRINTER_H
#define LLVM_LIB_TARGET_HCS08_MCTARGETDESC_HCS08INSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class HCS08InstPrinter : public MCInstPrinter {
public:
  HCS08InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                    const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printRegName(raw_ostream &O, MCRegister Reg) override;

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &O);
  void printCustomAliasOperand(const MCInst *MI, uint64_t Address,
                               unsigned OpIdx, unsigned PrintMethodIdx,
                               raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

private:
  void printImm8(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImm16(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBranchTarget(const MCInst *MI, uint64_t Address, unsigned OpNo,
                         raw_ostream &O);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_HCS08_MCTARGETDESC_HCS08INSTPRINTER_H
